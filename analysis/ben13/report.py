"""BEN-13 report: analysis/results/ben13/summary.json -> analysis/reports/ben13_s1_s2.md (every number read from the summary).

Tickets: BEN-13

    python -m analysis.ben13.report [--summary analysis/results/ben13/summary.json] [--out analysis/reports/ben13_s1_s2.md]

The report states the pre-registered predictions with their verdicts (plans/ben13_prereg.json), the reproduction rows,
and the share table: edge placement, label permutation, metric echo and the names channel (literature networks).
"""
import argparse, json
from pathlib import Path

HERE = Path(__file__).resolve().parents[2]


def f3(x):
    return "-" if x is None else ("%.3f" % x)


def rng(d):
    return "-" if not d else "%.3f [%.3f, %.3f]" % (d["mean"], d["lo"], d["hi"])


def build(s):
    L = ["# BEN-13: CausalBench shortcut audit, S0-S2 (MeanDifference)", "",
         "Tickets: BEN-13. Generated by `analysis/ben13/report.py` from `analysis/results/ben13/summary.json` "
         "(pre-registration sha256 %s...)." % s.get("prereg_sha256", "")[:12], "",
         "## Reproduction (S1)", "",
         "| line | cell | Wasserstein ours / published | FOR ours / published | within tolerance |", "|---|---|---|---|---|"]
    for line, x in s["lines"].items():
        for cell, r in (x.get("reproduction") or {}).items():
            pub = r.get("published") or {}
            L.append("| %s | %s | %s / %s | %s / %s | %s |" % (line, cell, f3(r["ours"]["wasserstein"]), f3(pub.get("wasserstein")),
                                                           f3(r["ours"]["for"]), f3(pub.get("for")), r["within_tolerance"]))
    L += ["", "All four rows within tolerance: **%s**. Fast evaluator equals causalbench's own: **%s**." % (
        s.get("reproduction_all"), s.get("fast_equals_full_all")), "",
          "## Share table (S2)", "",
          "Mean Wasserstein over a network's edges (higher = stronger knockdown effects on the predicted children).", "",
          "| line | k | MeanDifference | random | children rewired (same parents) | labels permuted | test-split ceiling | placement share | echo ratio |",
          "|---|---|---|---|---|---|---|---|---|"]
    for line, x in s["lines"].items():
        for k, c in (x.get("controls") or {}).items():
            md = (x.get("reproduction") or {}).get("md_%s" % k, {}).get("ours", {}).get("wasserstein")
            L.append("| %s | %s | %s | %s | %s | %s | %s | %s | %s |" % (
                line, k[1:], f3(md), rng((c.get("random") or {}).get("wasserstein")), rng((c.get("rewire_children") or {}).get("wasserstein")),
                rng((c.get("permute_labels") or {}).get("wasserstein")), f3(c.get("test_oracle_wasserstein")),
                f3(c.get("placement_share_wasserstein")), f3(c.get("echo_ratio"))))
    L += ["", "Placement share = (rewired - random) / (MeanDifference - random): the part of MeanDifference's above-random score "
          "that choosing strongly perturbing parents alone already earns. Echo ratio = MeanDifference / the same ranking computed "
          "on the test split (the ceiling of a total-effect ranking).", "",
          "False omission rate (FOR) shares:", ""]
    for line, x in s["lines"].items():
        for k, c in (x.get("controls") or {}).items():
            L.append("- %s k = %s: %s" % (line, k[1:], c.get("placement_share_for_note") or "placement share of FOR %s" % f3(c.get("placement_share_for"))))
    L += ["", "## Names channel: literature networks as predictions", "",
          "| line | network | edges | Wasserstein | same-size random | FOR | own precision when labels are permuted |", "|---|---|---|---|---|---|---|"]
    for line, x in s["lines"].items():
        for lit, r in (x.get("literature") or {}).items():
            if "edges" not in r:
                L.append("| %s | %s | not run: %s | | | | |" % (line, lit, (r.get("why") or r.get("status") or "")[:80]))
                continue
            L.append("| %s | %s | %d | %s | %s | %s | %s |" % (line, lit, r["edges"], f3(r["wasserstein"]),
                                                               rng((r.get("random_same_size") or {}).get("wasserstein")),
                                                               f3(r.get("for")) if r.get("for") is not None else "undefined",
                                                               rng((r.get("permuted") or {}).get("own_precision"))))
    L += ["", "FOR is undefined for a network whose path closure leaves fewer than 500 negative pairs (causalbench draws its "
          "negatives outside the closure; a dense network closes over nearly every pair).", "",
          "## Pre-registered predictions", "", "| | bar | verdict |", "|---|---|---|"]
    for k, v in (s.get("predictions") or {}).items():
        L.append("| %s | %s | **%s** |" % (k, v["bar"], v["verdict"]))
    L += ["", "Rule (pre-registered): share numbers are findings because S0 and S1 pass; a prediction with a missing cell is "
          "'not computed', never pass or fail.", ""]
    return "\n".join(L)


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--summary", default=str(HERE / "analysis" / "results" / "ben13" / "summary.json"))
    ap.add_argument("--out", default=str(HERE / "analysis" / "reports" / "ben13_s1_s2.md"))
    a = ap.parse_args(argv)
    s = json.loads(Path(a.summary).read_text())
    Path(a.out).write_text(build(s) + "\n", encoding="utf-8")
    print("wrote %s" % a.out)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
