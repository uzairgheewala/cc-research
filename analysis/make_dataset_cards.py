"""Freeze the Quarter 1 suite: write the suite manifest and one card per dataset (DLV-01, BND-05).

  python analysis/make_dataset_cards.py --date 2026-10-10

Writes
  manifests/evidence/suite_q1_<date>.sha256   every arm CSV, reference matrix and MAPPING of S1 and S2 (sha256sum format)
  docs/q1/datasets.md                         one card per dataset, generated from the MAPPINGs and reliability.json
A later change to any listed file fails the tracker's manifest check and reopens DLV-01 (failure mode F9).
"""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

WHY = {
    "sachs": "Pass 4b dataset. A widely published graph, so it tests whether the pipeline recalls a known answer; four name arms.",
    "abalone": "Ships in Causal-Copilot with a reference graph and matches an entry in CausalArena's real-data index.",
    "autompg": "Ships in Causal-Copilot with a reference graph; kept although it does not match CausalArena's Auto MPG.",
    "concrete": "Ships in Causal-Copilot with a reference graph and matches an entry in CausalArena's real-data index.",
    "dwd": "Ships in Causal-Copilot with a reference graph and matches an entry in CausalArena's real-data index.",
    "s2": "CausalArena semantic scenario from our test split (plans/splits.json): simulated, so the reference is exact; "
          "released in 2026, so the graph itself is unlikely to be memorised; columns shuffled because the release order "
          "is a topological order.",
}


def sha(p):
    return hashlib.sha256(Path(p).read_bytes()).hexdigest()


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--date", required=True)
    a = ap.parse_args()
    ds = ROOT / "datasets"
    p4b = json.loads((ds / "MAPPING.json").read_text(encoding="utf-8"))
    b1 = json.loads((ds / "suite_b1" / "MAPPING.json").read_text(encoding="utf-8"))
    s2 = json.loads((ds / "suite_q1s2" / "MAPPING.json").read_text(encoding="utf-8"))
    rel = json.loads((ROOT / "analysis" / "results" / "reference_reliability" / "reliability.json").read_text(encoding="utf-8"))

    listed = ["datasets/MAPPING.json", "datasets/suite_b1/MAPPING.json", "datasets/suite_q1s2/MAPPING.json",
              "analysis/results/reference_reliability/reliability.json"]
    for d in ["datasets/_reference", "datasets/suite_b1/_reference", "datasets/suite_q1s2/_reference"]:
        listed += sorted(str(p.relative_to(ROOT)).replace("\\", "/") for p in (ROOT / d).glob("*.npy"))
    for arm in p4b["arms"].values():
        listed.append(arm["dataset_arg"].split(":", 1)[1])
    for m in (b1, s2):
        for arm in m["arms"].values():
            listed.append(arm["dataset_arg"].split(":", 1)[1])
    listed = sorted(set(listed))
    # every arm's recorded hash must equal the file on disk
    bad = []
    for m in (p4b, b1, s2):
        for code, arm in m["arms"].items():
            f = ROOT / arm["dataset_arg"].split(":", 1)[1]
            if sha(f) != arm["sha256"]:
                bad.append(code)
    if bad:
        raise SystemExit("MAPPING hash differs from file for %s" % bad)
    man = ROOT / "manifests" / "evidence" / ("suite_q1_%s.sha256" % a.date)
    man.write_text("".join("%s  %s\n" % (sha(ROOT / f), f) for f in listed), encoding="utf-8")
    man_sha = sha(man)

    L = ["# Quarter 1 dataset suite", "",
         "Generated by `analysis/make_dataset_cards.py` on %s. Do not edit by hand." % a.date, "",
         "**Status: frozen.** Manifest `%s` (sha256 `%s`, %d files). Any change to a listed file fails the tracker's "
         "manifest check and reopens DLV-01 and every ticket that used the suite." % (man.relative_to(ROOT).as_posix(), man_sha, len(listed)), "",
         "| Suite | Datasets | Arms per dataset | Reference |", "|---|---|---|---|",
         "| S1 | Sachs; abalone, Auto MPG, concrete, DWD | Sachs: original, copy, neutral, moved; others: real, neutral, swapped | curated graphs shipped in Causal-Copilot |",
         "| S2 | 10 CausalArena semantic scenarios (test split) | real, neutral, swapped; columns shuffled | the simulating graph (exact) |", "",
         "Arms hold byte-identical numbers; only the header line differs. `real` = the dataset's own names, `neutral` = V01..Vnn, "
         "`swapped`/`moved` = the dataset's own names placed on the wrong columns by a derangement that minimises pairs adjacent in "
         "both the reference read by data and the reference read by label. Paths are opaque codes, so the file path tells the "
         "pipeline nothing.", "",
         "Reliability tiers (`analysis/results/reference_reliability/reliability.json`): **exact** = graph the data were simulated "
         "from; **contested** = published versions disagree; **provenance** = named source, nothing to compare against; "
         "**mismatched** = differs from the version a public benchmark uses.", ""]

    def armtable(rows):
        out = ["| Arm | Code | Labels | sha256 | Bytes |", "|---|---|---|---|---|"]
        out += ["| %s | `%s` | %s | `%s` | %d |" % r for r in rows]
        return out

    r = rel["families"]["sachs"]
    c = r["repo_vs_bnlearn"]
    L += ["## S1", "", "### Sachs (protein signalling)", "",
          "- **Source:** Causal-Copilot `%s` (sha256 `%s`), %d rows, %d variables: %s." % (
              p4b["source"]["file"], p4b["source"]["sha256"], p4b["source"]["rows"], len(p4b["source"]["columns"]), ", ".join(p4b["source"]["columns"])),
          "- **Reference:** `%s`, %d edges. **Tier: %s.** Compared with bnlearn's version (17 edges): %d shared adjacencies, "
          "%d same direction, %d reversed (%s); only in the repo: %s; only in bnlearn: %s. CausalArena uses a 20-edge version "
          "(`%s`) whose edge list is not available here." % (
              p4b["source"]["reference_graph"], len(p4b["source"]["reference_edges"]), r["tier"], c["shared_adjacencies"],
              c["same_direction"], c["reversed"], ", ".join(c["reversed_pairs_as_in_a"]), ", ".join(c["only_in_a"]),
              ", ".join(c["only_in_b"]), r["causalarena_version"]["graph_source"]),
          "- **Consequence:** %s" % r["consequence"],
          "- **Why chosen:** %s" % WHY["sachs"], ""]
    L += armtable([(k, k, "V01..V11" if v["column_labels"][0] == "V01" else (
                    "own names" if v["column_labels"] == v["data_in_each_column_is_really"] else "own names, moved"),
                    v["sha256"], v["bytes"]) for k, v in p4b["arms"].items()])
    L += [""]
    for fam, f in b1["families"].items():
        r = rel["families"][fam]
        L += ["### %s" % {"abalone": "Abalone", "autompg": "Auto MPG", "concrete": "Concrete compressive strength", "dwd": "Deutscher Wetterdienst"}[fam], "",
              "- **Source:** Causal-Copilot `%s` (sha256 `%s`), %d rows, %d variables: %s." % (
                  f["source_csv"], f["source_sha256"], f["rows"], len(f["columns"]), ", ".join(f["columns"])),
              "- **Reference:** `%s`, %d edges (%s). **Tier: %s.** Repo variables/edges/rows %s; CausalArena index %s. "
              "Shape: %d of %d edges touch `%s`." % (
                  f["reference"], len(f["reference_edges"]), ", ".join(f["reference_edges"]), r["tier"],
                  r["repo_vars_edges_rows"], r["causalarena_vars_edges_rows"],
                  round(r["shape"]["share_of_edges_touching_hub"] * len(f["reference_edges"])), len(f["reference_edges"]), r["shape"]["max_degree_node"]),
              "- **Consequence:** %s" % r["consequence"],
              "- **Why chosen:** %s" % WHY[fam],
              "- **Swapped arm:** %d adjacent pair(s) shared by the two readings of the reference." % f["adjacent_pairs_shared_by_the_two_references"], ""]
        L += armtable([(b1["arms"][code]["role"], code, ", ".join(b1["arms"][code]["column_labels"]), b1["arms"][code]["sha256"], b1["arms"][code]["bytes"])
                       for code in f["arms"].values()])
        L += [""]
    L += ["## S2", "",
          "Source for every S2 dataset: replicate 0 of CausalArena's observational-only semantic release; values are the release's "
          "standardised float32 values written with 9 significant digits (exact round trip). Builder: `analysis/make_suite_ca.py`, "
          "gates D1-D10 all pass (recorded per family in `datasets/suite_q1s2/MAPPING.json`). Every scenario is in the test split "
          "and must not be used for tuning (F3).", ""]
    for fam, f in s2["families"].items():
        r = rel["families"][fam]
        L += ["### %s: %s" % (fam, f["scenario_name"]), "",
              "- **Source:** `%s` (sha256 `%s`); domain %s; %d rows, %d variables." % (
                  f["source_npz"], f["source_sha256"], f["domain_id"], f["rows"], f["variables"]),
              "- **Reference:** the release's graph, %d edges, identical to `%s` read by name and to replicates 1-4. **Tier: %s.**" % (
                  f["edges"], f["graph_json"], r["tier"]),
              "- **Column order:** shuffled (seed string `%s`); edges running earlier to later column: %.0f%% released, %.0f%% here." % (
                  f["shuffle_seed_string"], 100 * f["share_edges_earlier_to_later"]["released"], 100 * f["share_edges_earlier_to_later"]["csv"]),
              "- **Swapped arm:** %d adjacent pair(s) shared by the two readings (%s)." % (
                  f["adjacent_pairs_shared_by_the_two_references"],
                  "proved minimal" if f["search_proved_minimal"] else "best found within the search budget, not proved minimal"),
              "- **Consequence:** %s" % r["consequence"],
              "- **Why chosen:** %s" % WHY["s2"], ""]
        L += armtable([(s2["arms"][code]["role"], code, "%d labels" % len(s2["arms"][code]["column_labels"]), s2["arms"][code]["sha256"], s2["arms"][code]["bytes"])
                       for code in f["arms"].values()])
        L += [""]
    (ROOT / "docs" / "q1" / "datasets.md").write_text("\n".join(L), encoding="utf-8")
    print("manifest %s (%d files, sha256 %s); cards: %d S1 + %d S2" % (man.name, len(listed), man_sha, 1 + len(b1["families"]), len(s2["families"])))


if __name__ == "__main__":
    main()
